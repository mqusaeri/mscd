/** A path of a route with its `:name` segments filled in. */
export function pathOf(route: RouteRef, params: Record<string, string>): string {
  return route[1].replace(/:([a-zA-Z]+)/g, (_m, name: string) => encodeURIComponent(params[name] ?? ''));
}
